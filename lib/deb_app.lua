-- Shared logic for desktop apps their vendors ship only as an apt repository:
-- read the repository's Packages index, fetch the .deb from its pool, unpack it
-- into the mise install dir and add a Wayland-aware launcher and a .desktop entry.
local http = require("http")
local cmd = require("cmd")

local M = {}

local function index(app)
    local resp, err = http.get({ url = app.repo .. "/dists/stable/main/binary-amd64/Packages" })
    if err ~= nil or resp.status_code ~= 200 then
        error("cannot read the package index of " .. app.repo .. ": " .. tostring(err or resp.status_code))
    end
    local entries = {}
    for stanza in (resp.body .. "\n\n"):gmatch("(.-)\n\n") do
        local fields = {}
        for k, v in stanza:gmatch("([%w%-]+): ([^\n]*)") do
            fields[k] = v
        end
        if fields.Package == app.package and fields.Version then
            table.insert(entries, fields)
        end
    end
    return entries
end

local function compare(a, b)
    local pa, pb = {}, {}
    for n in a:gmatch("%d+") do table.insert(pa, tonumber(n)) end
    for n in b:gmatch("%d+") do table.insert(pb, tonumber(n)) end
    for i = 1, math.max(#pa, #pb) do
        local x, y = pa[i] or 0, pb[i] or 0
        if x ~= y then return x < y end
    end
    return false
end

function M.available(app)
    local seen, versions = {}, {}
    for _, e in ipairs(index(app)) do
        if not seen[e.Version] then
            seen[e.Version] = true
            table.insert(versions, e.Version)
        end
    end
    table.sort(versions, compare)
    local result = {}
    for i = #versions, 1, -1 do
        table.insert(result, { version = versions[i] })
    end
    return result
end

function M.pre_install(app, version)
    for _, e in ipairs(index(app)) do
        if e.Version == version then
            return { version = version, url = app.repo .. "/" .. e.Filename, sha256 = e.SHA256 }
        end
    end
    error(app.package .. " " .. version .. " is not in " .. app.repo)
end

local function write(path, content, mode)
    local f = assert(io.open(path, "w"))
    f:write(content)
    f:close()
    if mode then cmd.exec("chmod " .. mode .. " '" .. path .. "'") end
end

local launcher = [==[#!/bin/bash
# Generated by the %s mise plugin.
# Ask Electron for Wayland on a Wayland session unless a platform flag is given;
# extra flags come from ~/.config/%s, one or more per line.
set -euo pipefail
flags=()
conf="${XDG_CONFIG_HOME:-$HOME/.config}/%s"
if [[ -r $conf ]]; then
  while IFS= read -r line || [[ -n $line ]]; do
    line="${line%%%%#*}"
    [[ -n ${line//[[:space:]]/} ]] || continue
    read -r -a words <<<"$line"
    flags+=("${words[@]}")
  done <"$conf"
fi
platform=()
if [[ -n ${WAYLAND_DISPLAY:-} || ${XDG_SESSION_TYPE:-} == wayland ]]; then
  platform=(--ozone-platform=wayland)
  for f in "${flags[@]}" "$@"; do
    case $f in --ozone-platform=* | --ozone-platform-hint=*) platform=() ;; esac
  done
fi
exec "$(dirname "$(readlink -f "$0")")/../%s" "${platform[@]}" "${flags[@]}" "$@"
]==]

function M.post_install(app, root)
    -- mise leaves an unknown archive type as the downloaded file in the install dir.
    local deb = cmd.exec("find '" .. root .. "' -maxdepth 1 -name '*.deb' -print -quit"):gsub("%s+$", "")
    if deb == "" then error("no .deb downloaded into " .. root) end
    cmd.exec("bsdtar -xOf '" .. deb .. "' 'data.tar.*' | bsdtar --no-same-owner -xf - -C '" .. root .. "'")
    cmd.exec("rm -f '" .. deb .. "'; rm -rf '" .. root .. "/usr/share/doc' '" .. root .. "/usr/share/lintian' '" .. root .. "/etc'")

    cmd.exec("mkdir -p '" .. root .. "/bin'")
    write(root .. "/bin/" .. app.tool, launcher:format(app.tool, app.flags_file, app.flags_file, app.binary), "755")

    -- The entry points at the tool's "latest" link, so it survives upgrades and keeps
    -- the vendor's desktop-file id, which shadows a system package's entry of that id.
    local home = os.getenv("HOME")
    local data = os.getenv("MISE_DATA_DIR") or (home .. "/.local/share/mise")
    local stable = data .. "/installs/" .. app.tool .. "/latest"
    local src = root .. "/usr/share/applications/" .. app.desktop_id
    local f = io.open(src, "r")
    if f then
        local entry = f:read("*a"):gsub("\nExec=[^ \n]+", "\nExec=" .. stable .. "/bin/" .. app.tool)
        f:close()
        entry = entry:gsub("\nIcon=[^\n]+", "\nIcon=" .. stable .. "/" .. app.icon)
        local dir = home .. "/.local/share/applications"
        cmd.exec("mkdir -p '" .. dir .. "'")
        write(dir .. "/" .. app.desktop_id, entry)
        cmd.exec("update-desktop-database -q '" .. dir .. "' || true")
    end
end

return M
